// Regenerates src/theme/template.css and src/theme/template-tokens.css from the UAB template
// (template/FE/clinic-ops-admin/src). Every class selector gets the `uab-` prefix so the template's
// rules cannot collide with Tailwind utilities; the two token names that collide with ours are renamed.
// Usage: node scripts/build-template-css.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = dirname(fileURLToPath(import.meta.url));
const template = join(here, '../../../template/FE/clinic-ops-admin/src');
const outDir = join(here, '../src/theme');
const PREFIX = 'uab-';
const RENAMED_TOKENS = { '--z-sticky': '--uab-z-sticky', '--z-toast': '--uab-z-toast' };

/** Prefixes `.class` selectors, leaving quoted strings and [attribute] selectors alone. */
function prefixSelector(selector) {
  let out = '';
  let bracket = 0;
  let quote = '';
  for (let i = 0; i < selector.length; i += 1) {
    const ch = selector[i];
    if (quote) {
      out += ch;
      if (ch === quote) quote = '';
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      out += ch;
      continue;
    }
    if (ch === '[') bracket += 1;
    if (ch === ']') bracket -= 1;
    out += ch;
    if (ch === '.' && bracket === 0 && /[_a-zA-Z-]/.test(selector[i + 1] ?? '')) out += PREFIX;
  }
  return out;
}

function renameTokens(css) {
  return Object.entries(RENAMED_TOKENS).reduce(
    (text, [from, to]) => text.replaceAll(new RegExp(`${from}(?![\\w-])`, 'g'), to),
    css,
  );
}

const banner = (source) =>
  `/* GENERATED by scripts/build-template-css.mjs from ${source}. Do not edit by hand: edit the template and regenerate. */\n`;

const tokens = renameTokens(readFileSync(join(template, 'tokens/tokens.css'), 'utf8'));
writeFileSync(join(outDir, 'template-tokens.css'), banner('tokens/tokens.css') + tokens);

const root = postcss.parse(renameTokens(readFileSync(join(template, 'styles/app.css'), 'utf8')));
root.walkRules((rule) => {
  if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  rule.selector = prefixSelector(rule.selector);
});
writeFileSync(join(outDir, 'template.css'), banner('styles/app.css') + root.toString());
console.log('Wrote template-tokens.css and template.css');
